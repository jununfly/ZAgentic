"""zj-dp-driven 可视化 (§6) — Mermaid 渲染器（Phase-3c）。

Design baseline: docs/designs/zj-dp-driven-skill-design.md §6 (R1–R6) / §8 未决→已定。

Backend: **Mermaid `flowchart TD` text** generated by stdlib only. Chosen over static
HTML+dagre, Graphviz dot, and terminal ASCII because: (a) zero new deps — mirrors the
carrier/optimizer stdlib stance; (b) the output is greppable/diffable text so every visual
claim is a *failing test*, not a screenshot hope; (c) it renders in GitHub/VSCode md viewers
with no install; (d) adopting a vendored layout JS would mirror `zj-roadmap-driven/viz/`
and drift toward the old pair, which this skill's build-period discipline forbids.

R7 (interactive right-region card) is deliberately NOT here: the existing read commands
(`status` / `task view` / `node_view`) are the CLI form of "click → details"; HTML
interactivity is deferred (design §6 [未决] R7 / §8).

Invariants honored:
* **read-only + deterministic** (§3.1 / §3.6): `render()` calls only existing derived reads
  (pool / node_view / task_view / claim_owner / _plan_inner_nodes / in_flight_plans /
  find_memberships) and never mutates or saves. Same model.data ⇒ byte-equal output
  (everything iterated in sorted order, no wall clock).
* **blocked is displayed from the derived view, never read as a stored field** (§3.2).
* **shared finding is drawn once per plan with an overlap marker and NO cross-plan
  "who overlaps whom" edges** (§3.6 F1 / §6 R6 取巧渲染).
"""

from __future__ import annotations

from dp_driven_model import (
    CLAIM_PLAN, DpDriven, KIND_FINDING, KIND_TICKET, SETTLEMENT_AGENT,
    S_ABANDONED, S_BLOCKED, S_DONE, S_OPEN,
)

# classDef contract (mirrored in references/dp_driven-viz.md)
_CLASSDEFS = (
    "  classDef open fill:#f6f8fa,stroke:#656d76,color:#0f172a",
    "  classDef done fill:#dafbe1,stroke:#1a7f37,color:#0f172a",
    "  classDef abandoned fill:#f6f8fa,stroke:#656d76,stroke-dasharray:3 3,color:#57606a",
    "  classDef blocked fill:#fff8c5,stroke:#9a6704,color:#0f172a",
    "  classDef overlap fill:#ffebe9,stroke:#cf222e,color:#cf222e",
    "  classDef plan_inflight stroke:#1a7f37,stroke-width:2px",
    "  classDef plan_paused stroke:#8250df,stroke-width:2px,stroke-dasharray:5 5",
    "  classDef plan_settlement stroke:#656d76,stroke-dasharray:2 2",
)

_ORPHAN_SUBGRAPH = "ORPHANS"


def _clean(text: str) -> str:
    """Strip Mermaid label-breaking chars; deterministic."""
    out = str(text)
    for ch in ('"', "[", "]", "{", "}", "`", "<", ">"):
        out = out.replace(ch, "")
    return out.replace("\n", " ").strip()


def _short_id(kind: str, nid: int) -> str:
    return ("tk" if kind == KIND_TICKET else "f") + str(nid)


def _node_mid(kind: str, nid: int, plan: int | None) -> str:
    """Unique Mermaid node id for an item *instance* inside a plan (or the orphan bucket)."""
    sid = _short_id(kind, nid)
    return f"{sid}_T{plan}" if plan is not None else f"{sid}_ORPHAN"


def _canonical_mid(model: DpDriven, kind: str, nid: int) -> str:
    """Edge endpoints reference ONE canonical instance per node (§6 R6: no cross-plan
    overlap links). Ticket → its owner; finding → its lowest-membership plan; else orphan."""
    if kind == KIND_TICKET:
        owner = model._require_ticket(nid).get("task_id")
        return _node_mid(kind, nid, owner)
    members = model.find_memberships(nid)
    return _node_mid(kind, nid, min(members)) if members else _node_mid(kind, nid, None)


def _display_status(model: DpDriven, kind: str, nid: int) -> str:
    """Item's shown status. blocked comes from the DERIVED view (§3.2), never a stored read."""
    nv = model.node_view(kind, nid)
    return S_BLOCKED if nv.get("blocked") else nv["status"]


def _status_class(status: str) -> str:
    return {S_DONE: "done", S_ABANDONED: "abandoned", S_BLOCKED: "blocked"}.get(status, "open")


def _plan_claim_class(model: DpDriven, tid: int) -> str | None:
    """R5 claim visualization: in-flight (claimed by a real agent) vs paused (open, no claim)
    vs settlement sentinel. Terminal plans get no emphasis class."""
    plan = model.data["plans"][str(tid)]
    if plan["status"] != S_OPEN:
        return None
    owner = model.claim_owner(CLAIM_PLAN, tid)
    if owner == SETTLEMENT_AGENT:
        return "plan_settlement"
    if owner is not None:
        return "plan_inflight"
    return "plan_paused"


def _multi_membership(model: DpDriven) -> set[int]:
    from collections import defaultdict
    by_f = defaultdict(set)
    for m in model.data["memberships"]:
        by_f[m["finding_id"]].add(m["task_id"])
    return {fid for fid, plans in by_f.items() if len(plans) > 1}


def render(model: DpDriven) -> str:
    """Return Mermaid `flowchart TD` text for the current DP state graph (§6). Pure read."""
    lines = ["flowchart TD", *_CLASSDEFS, ""]
    lines.append(f"  %% destination: {_clean(model.data['meta'].get('destination', ''))}")

    tasks = sorted(model.data["tasks"].values(), key=lambda x: x["id"])
    findings = sorted(model.data["findings"].values(), key=lambda x: x["id"])
    tickets = sorted(model.data["tickets"].values(), key=lambda x: x["id"])
    edge_list = sorted(model.data["edges"], key=lambda x: x["id"])
    multi = _multi_membership(model)

    # ── R1/R2: one subgraph per task-plan, holding that plan's layer-2 items ──
    for t in tasks:
        tid = t["id"]
        tv = model.task_view(tid)
        lines.append(f'  subgraph T{tid}["task{tid} {_clean(t["name"])} ({tv["status"]})"]')
        lines.append("    direction TB")
        members = model._plan_inner_nodes(tid)
        for (kind, nid) in sorted(members):
            disp = _display_status(model, kind, nid)
            cls = _status_class(disp)
            overlap = kind == KIND_FINDING and nid in multi
            if overlap:
                cls = "overlap"   # §6 R6 异色 + 角标优先于状态色
            suffix = " ⟲" if overlap else ""
            label = f'{_short_id(kind, nid)} {disp}{suffix}'
            mid = _node_mid(kind, nid, tid)
            lines.append(f'    {mid}["{label}"]:::{cls}')
        pcls = _plan_claim_class(model, tid)
        if pcls:
            lines.append(f"    class T{tid} {pcls}")
        lines.append("  end")

    # ── R4: orphan items (no plan membership / unclaimed) in a separate subgraph ──
    in_any_plan: set = set()
    for t in tasks:
        in_any_plan |= model._plan_inner_nodes(t["id"])
    orphans = []
    for f in findings:
        if (KIND_FINDING, f["id"]) not in in_any_plan:
            orphans.append((KIND_FINDING, f["id"], f))
    for k in tickets:
        if k.get("task_id") is None and (KIND_TICKET, k["id"]) not in in_any_plan:
            orphans.append((KIND_TICKET, k["id"], k))
    if orphans:
        lines.append(f'  subgraph {_ORPHAN_SUBGRAPH}["Orphan findings / 未收纳 items (R4)"]')
        lines.append("    direction TB")
        for (kind, nid, node) in sorted(orphans, key=lambda o: (o[0], o[1])):
            disp = _display_status(model, kind, nid)
            label = f'{_short_id(kind, nid)} {disp}'
            mid = _node_mid(kind, nid, None)
            lines.append(f'    {mid}["{label}"]:::{_status_class(disp)}')
        lines.append("  end")

    # ── edges (each drawn once, canonical endpoints) ──
    # R2 blocks (依赖)
    for e in edge_list:
        if e["type"] != "blocks":
            continue
        s = _canonical_mid(model, e["from_kind"], e["from_id"])
        d = _canonical_mid(model, e["to_kind"], e["to_id"])
        lines.append(f"  {s} -->|blocks| {d}")
    # R2 parent (父子, never blocks)
    for k in tickets:
        if k.get("parent_id") is not None:
            s = _canonical_mid(model, KIND_TICKET, k["parent_id"])
            d = _canonical_mid(model, KIND_TICKET, k["id"])
            lines.append(f"  {s} -->|parent| {d}")
    # R2 materialization: ticket.derived_from_finding (①) + finding.derived_from_finding (②)
    for k in tickets:
        if k.get("derived_from_finding") is not None:
            s = _canonical_mid(model, KIND_FINDING, k["derived_from_finding"])
            d = _canonical_mid(model, KIND_TICKET, k["id"])
            lines.append(f"  {s} -.->|derived_from| {d}")
    for f in findings:
        if f.get("derived_from_finding") is not None:
            s = _canonical_mid(model, KIND_FINDING, f["derived_from_finding"])
            d = _canonical_mid(model, KIND_FINDING, f["id"])
            lines.append(f"  {s} -.->|derived_from| {d}")

    # ── R1: layer-1 task→task-plan = quotient of cross-plan blocks edges (§3.6 F2) ──
    quotient = set()
    for e in edge_list:
        if e["type"] != "blocks":
            continue
        sp = _plan_of(model, e["from_kind"], e["from_id"])
        dp = _plan_of(model, e["to_kind"], e["to_id"])
        if sp is not None and dp is not None and sp != dp:
            quotient.add((sp, dp))
    for a, b in sorted(quotient):
        lines.append(f"  T{a} -->|plan-dep| T{b}")

    # form-③ task.derived_from_finding → links a finding to a whole new task-region
    for t in tasks:
        if t.get("derived_from_finding") is not None:
            s = _canonical_mid(model, KIND_FINDING, t["derived_from_finding"])
            lines.append(f"  {s} -.->|origin(form-③)| T{t['id']}")

    return "\n".join(lines) + "\n"


def _plan_of(model: DpDriven, kind: str, nid: int) -> int | None:
    if kind == KIND_TICKET:
        return model._require_ticket(nid).get("task_id")
    members = model.find_memberships(nid)
    return min(members) if members else None


def render_to_file(model: DpDriven, out_path: str) -> str:
    """Write the Mermaid text to out_path (sibling of the carrier, process-zone; §5.4).
    Writes only to the given path — never elsewhere. Returns the path."""
    text = render(model)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return out_path


def default_out_path(db_path: str) -> str:
    base = db_path
    for ext in (".sqlite", ".sqlite3", ".db"):
        if base.endswith(ext):
            base = base[: -len(ext)]
            break
    return base + ".mmd"
