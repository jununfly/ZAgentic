#!/usr/bin/env python3
"""Deterministic maintainer for the roadmap visual-review technical design.

The technical design page is a *derived view* of ``docs/designs/zj-roadmap-visual-review.spec.json``.
Nothing in that page is hand-authored: ``render`` writes it, ``verify`` checks it
byte-for-byte, and ``validate`` applies the mechanical gates before either is allowed.

Shapes borrowed from ``zj-graphical-cross-comparison`` (CHK-04 scene externality,
CHK-06 supply-state evidence, CHK-09 source labelling, CHK-12 difference-entry
cardinality). This script does NOT sign a cross-comparison report: the scene set is
an Agent transcription of a Human utterance and is explicitly not independently
pinned (see ``scene-set.human-independent-pin``).

Design constraints:
  * stdlib only (JSON is a first-class SoT, no PyYAML needed).
  * No explicit --out means *no file is written* (ADR 0010).
  * Rendering is deterministic: no timestamps, no absolute paths, no random layout.
  * Diagnostics go to stdout; ERROR-level findings exit 1.
  * Summary metrics are display-only and must never drive a conclusion.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

SCHEMA = "zj-roadmap-visual-review/spec/v1"
GENERATED_MARKER = "<!-- GENERATED BY scripts/roadmap_visual_review_spec.py; DO NOT EDIT -->"
DEFAULT_SPEC = "docs/designs/zj-roadmap-visual-review.spec.json"
DEFAULT_TECH_MD = "docs/designs/zj-roadmap-visual-review-technical.md"
DEFAULT_PRODUCT_MD = "docs/designs/zj-roadmap-visual-review-product.md"

SUPPLY_STATES = {"native", "adapted", "unsupported", "unknown"}
CONTEXT_STATES = {"satisfied", "violated", "unknown"}
SOURCE_KINDS = {"evidence", "human-ruling", "assumption"}
PRIMARY_KINDS = {"primary", "secondary"}

ID_PREFIXES = {
    "load-conditions": "LC::",
    "context-entries": "CTX::",
    "projects": "P",
    "difference-entries": "DE::",
    "capabilities": "C::",
    "view-contracts": "VC::",
    "invariants": "INV::",
    "slices": "S",
    "rejected-defaults": "RD::",
    "sources": "E::",
}


class Gate:
    """Collects diagnostics without deciding anything on behalf of the Human."""

    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, code: str, msg: str) -> None:
        self.errors.append(f"ERROR: [{code}] {msg}")

    def warn(self, code: str, msg: str) -> None:
        self.warnings.append(f"WARN: [{code}] {msg}")

    def ok(self) -> bool:
        return not self.errors


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def load_spec(repo_root: Path, spec_rel: str) -> dict:
    path = repo_root / spec_rel
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def ids_of(spec: dict, key: str) -> list[str]:
    return [item["id"] for item in spec.get(key, [])]


def scene_ids(spec: dict) -> list[str]:
    """Scenes live under scene-set, not at the top level (external reference set)."""
    return [item["id"] for item in spec.get("scene-set", {}).get("scenes", [])]


def ref_set(spec: dict) -> set[str]:
    """All IDs that may legally appear in a *-ref / *-refs field."""
    return set(ids_of(spec, "sources")) | set(scene_ids(spec)) | \
        set(ids_of(spec, "context-entries")) | set(ids_of(spec, "projects")) | \
        set(ids_of(spec, "capabilities")) | set(ids_of(spec, "view-contracts")) | \
        set(ids_of(spec, "invariants")) | set(ids_of(spec, "slices")) | \
        set(ids_of(spec, "rejected-defaults")) | set(ids_of(spec, "difference-entries"))


def source_kind(spec: dict, ref: str) -> str | None:
    for item in spec.get("sources", []):
        if item["id"] == ref:
            return item.get("kind")
    return None


