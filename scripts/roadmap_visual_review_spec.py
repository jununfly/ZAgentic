def _resolve(repo_root: Path, value: str | None, default: str) -> Path:
    path = Path(value or default)
    return path if path.is_absolute() else repo_root / path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["validate", "render", "verify", "metrics"])
    parser.add_argument("--repo-root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--spec", default=DEFAULT_SPEC)
    parser.add_argument("--md", default=DEFAULT_TECH_MD)
    parser.add_argument("--product-md", default=DEFAULT_PRODUCT_MD)
    parser.add_argument("--out", default=None, help="explicit output path; without it no file is written")
    args = parser.parse_args(argv)

    root = Path(args.repo_root)
    try:
        spec = load_spec(root, args.spec)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: [LOAD] cannot read spec: {exc}")
        return 1

    gate = Gate()
    validate(spec, gate)

    if args.command == "validate":
        for line in gate.errors + gate.warnings:
            print(line)
        if gate.ok():
            print(f"OK: {len(spec.get('difference-entries', []))} difference-entries, "
                  f"0 ERROR, {len(gate.warnings)} WARN; no signed cross-comparison report "
                  f"(human-independent-pin=false)")
        return 0 if gate.ok() else 1

    if args.command == "metrics":
        print(json.dumps(metrics(spec), ensure_ascii=False, indent=2, sort_keys=True))
        return 0

    if not gate.ok():
        for line in gate.errors:
            print(line)
        print("ERROR: [GATE] spec failed validate; refusing to render / verify")
        return 1

    expected = render(spec)

    if args.command == "render":
        if args.out is None:
            sys.stdout.write(expected)
            return 0
        out = _resolve(root, args.out, DEFAULT_TECH_MD)
        with out.open("w", encoding="utf-8") as handle:  # direct write, no atomic replace
            handle.write(expected)
        print(f"OK: wrote {out.relative_to(root) if out.is_relative_to(root) else out}")
        return 0

    # verify
    md_path = _resolve(root, args.md, DEFAULT_TECH_MD)
    if not md_path.exists():
        print(f"ERROR: [VERIFY] technical page missing: {md_path}")
        return 1
    actual = md_path.read_text(encoding="utf-8")
    if actual != expected:
        print(f"ERROR: [VERIFY] {md_path} drifted from spec; run render --out to regenerate")
        return 1
    product_path = _resolve(root, args.product_md, DEFAULT_PRODUCT_MD)
    if product_path.exists() and GENERATED_MARKER in product_path.read_text(encoding="utf-8"):
        print(f"ERROR: [VERIFY] hand-authored product page must not carry the generated marker: {product_path}")
        return 1
    print(f"OK: {md_path.name} is byte-identical to the spec projection")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
