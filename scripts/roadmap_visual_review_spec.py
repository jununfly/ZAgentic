def metrics(spec: dict) -> dict:
    des = spec.get("difference-entries", [])
    ctx_verdicts = [v for de in des for v in de.get("context-verdicts", [])]
    bound = sum(1 for de in des if de.get("evidence-refs"))
    return {
        "schema": "zj-roadmap-visual-review/metrics/v1",
        "usage": "display-only",
        "not_for_conclusion": True,
        "scenes": len(spec.get("scene-set", {}).get("scenes", [])),
        "projects": len(spec.get("projects", [])),
        "difference_entries": len(des),
        "verdict_distribution": dict(sorted(Counter(de.get("verdict") for de in des).items())),
        "context_verdict_distribution": dict(sorted(Counter(v.get("verdict") for v in ctx_verdicts).items())),
        "evidence_binding_coverage": round(bound / len(des), 4) if des else 0.0,
        "capabilities": len(spec.get("capabilities", [])),
        "view_contracts": len(spec.get("view-contracts", [])),
        "invariants": len(spec.get("invariants", [])),
        "load_conditions": len(spec.get("load-conditions", [])),
        "doi_terms": len(spec.get("information-selection", {}).get("doi-function", {}).get("terms", [])),
        "reading_budget_max": spec.get("information-selection", {}).get("reading-budget", {}).get("max"),
        "debt_kinds": len(spec.get("debt-schema", {}).get("kinds", [])),
        "presentation_regions": len(spec.get("presentation", {}).get("three-regions", [])),
        "card_lod_levels": len(spec.get("presentation", {}).get("card-lod", {}).get("levels", [])),
        "sources_primary": sum(1 for s in spec.get("sources", []) if s.get("kind") == "primary"),
        "sources_secondary": sum(1 for s in spec.get("sources", []) if s.get("kind") == "secondary"),
        "human_independent_pin": spec.get("scene-set", {}).get("human-independent-pin"),
    }


