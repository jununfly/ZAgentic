def validate(spec: dict, gate: Gate) -> None:
    _r1_schema_and_ids(spec, gate)
    _r2_scene_externality(spec, gate)
    _r3_difference_cardinality(spec, gate)
    _r4_supply_state(spec, gate)
    _r5_context_state(spec, gate)
    _r6_reference_closure(spec, gate)
    _r7_capability_coverage(spec, gate)
    _r8_invariants(spec, gate)
    _r9_source_labelling(spec, gate)
    _r10_evidence_integrity(spec, gate)
    _r11_derivation_shape(spec, gate)
    _r12_problem_refinement(spec, gate)
    _r13_doi_function(spec, gate)
    _r14_budget_and_debt(spec, gate)
    _r15_reentry(spec, gate)
    _r16_presentation(spec, gate)


def _r1_schema_and_ids(spec: dict, gate: Gate) -> None:
    if spec.get("schema") != SCHEMA:
        gate.error("R1", f"schema must be {SCHEMA!r}, got {spec.get('schema')!r}")
    if not spec.get("version-pin"):
        gate.error("R1", "version-pin is empty")
    for role in ("product", "technical"):
        val = spec.get("authority-ids", {}).get(role, "")
        if not val.startswith("design."):
            gate.error("R1", f"authority-ids.{role} must be a design.* id, got {val!r}")

    all_ids: list[str] = []
    for key, prefix in ID_PREFIXES.items():
        for item in spec.get(key, []):
            iid = item.get("id", "")
            if not iid:
                gate.error("R1", f"{key} has an item without id")
                continue
            if not iid.startswith(prefix):
                gate.error("R1", f"{key} id {iid!r} must start with {prefix!r}")
            all_ids.append(iid)
    for item in spec.get("scene-set", {}).get("scenes", []):
        iid = item.get("id", "")
        if not iid.startswith("SC::"):
            gate.error("R1", f"scene id {iid!r} must start with 'SC::'")
        all_ids.append(iid)
    dupes = [iid for iid, count in Counter(all_ids).items() if count > 1]
    if dupes:
        gate.error("R1", f"duplicate ids: {sorted(dupes)}")


def _r2_scene_externality(spec: dict, gate: Gate) -> None:
    """CHK-04: the scene set is external to the project graphs."""
    scene_set = spec.get("scene-set", {})
    if scene_set.get("derived-from-graphs") is not False:
        gate.error("R2", "scene-set.derived-from-graphs must be false")
    if not scene_set.get("source"):
        gate.error("R2", "scene-set.source is empty")
    if not scene_set.get("version-pin"):
        gate.error("R2", "scene-set.version-pin is empty")
    if scene_set.get("human-independent-pin") is not False:
        gate.warn("R2", "human-independent-pin is true; a signed report now requires Human verification of the pin")
    forbidden = {"nodes", "modules", "members", "node-set", "view-kind"}
    for scene in scene_set.get("scenes", []):
        for field in ("start", "end", "observable"):
            if not isinstance(scene.get(field), str) or not scene.get(field).strip():
                gate.error("R2", f"scene {scene.get('id')!r} has empty {field}")
        overlap = forbidden & set(scene)
        if overlap:
            gate.error("R2", f"scene {scene.get('id')!r} prescribes implementation fields: {sorted(overlap)}")


def _r3_difference_cardinality(spec: dict, gate: Gate) -> None:
    """CHK-12: (scene, project) must be exactly the full cartesian product."""
    scenes = set(scene_ids(spec))
    projects = set(ids_of(spec, "projects"))
    expected = {(s, p) for s in scenes for p in projects}
    seen: list[tuple[str, str]] = []
    for de in spec.get("difference-entries", []):
        key = (de.get("scene"), de.get("project"))
        if key[0] not in scenes:
            gate.error("R3", f"{de.get('id')} references unknown scene {key[0]!r}")
        if key[1] not in projects:
            gate.error("R3", f"{de.get('id')} references unknown project {key[1]!r}")
        seen.append(key)
    counts = Counter(seen)
    for key in sorted(expected - set(seen), key=lambda x: (x[1], x[0])):
        gate.error("R3", f"missing difference-entry for scene={key[0]} project={key[1]}")
    for key, count in sorted(counts.items()):
        if count > 1:
            gate.error("R3", f"duplicate difference-entry for {key}: {count}")
    for key in sorted(set(seen) - expected):
        gate.error("R3", f"overflow difference-entry for {key}")
    if len(seen) != len(expected):
        gate.error("R3", f"cardinality {len(seen)} != |scenes| x |projects| = {len(expected)}")


def _r4_supply_state(spec: dict, gate: Gate) -> None:
    """CHK-06: every supply state is bound to the right kind of evidence."""
    source_ids = set(ids_of(spec, "sources"))
    for de in spec.get("difference-entries", []):
        did = de.get("id")
        verdict = de.get("verdict")
        refs = de.get("evidence-refs", [])
        if verdict not in SUPPLY_STATES:
            gate.error("R4", f"{did} invalid verdict {verdict!r}")
            continue
        for ref in refs:
            if ref not in source_ids:
                gate.error("R4", f"{did} evidence-ref {ref!r} is not a declared source")
            if source_kind(spec, ref) == "secondary" and verdict == "native" and len(refs) == 1:
                gate.error("R4", f"{did} native rests solely on a secondary source {ref!r}")
        if verdict in ("native", "adapted") and not refs:
            gate.error("R4", f"{did} verdict={verdict} requires non-empty evidence-refs")
        if verdict == "adapted" and not de.get("adaptation-target"):
            gate.error("R4", f"{did} adapted requires an adaptation-target")
        if verdict == "unsupported" and not de.get("negative-statement-ref"):
            gate.error("R4", f"{did} unsupported requires an explicit negative-statement-ref")
        if verdict == "unknown" and not de.get("verification-plan"):
            gate.error("R4", f"{did} unknown requires a verification-plan (it is an evidence gap, not a negation)")
        if verdict == "unknown" and refs:
            gate.error("R4", f"{did} unknown must not carry coverage evidence")


def _r5_context_state(spec: dict, gate: Gate) -> None:
    """CHK-10: context entries are side-lists, never graph members."""
    ctx_ids = set(ids_of(spec, "context-entries"))
    for de in spec.get("difference-entries", []):
        did = de.get("id")
        refs = de.get("context-refs", [])
        verdicts = de.get("context-verdicts", [])
        vrefs = [v.get("ref") for v in verdicts]
        if set(refs) != set(vrefs) or len(refs) != len(vrefs):
            gate.error("R5", f"{did} context-verdicts.ref set must equal context-refs exactly")
        for ref in refs:
            if ref not in ctx_ids:
                gate.error("R5", f"{did} context-ref {ref!r} is not a declared context-entry")
        for v in verdicts:
            if v.get("verdict") not in CONTEXT_STATES:
                gate.error("R5", f"{did} invalid context verdict {v.get('verdict')!r}")
            if v.get("verdict") == "violated" and not v.get("evidence-ref"):
                gate.error("R5", f"{did} violated requires explicit negative evidence")
    for ctx in spec.get("context-entries", []):
        if ctx.get("scope") != "domain":
            gate.error("R5", f"{ctx.get('id')} scope must be domain in this spec")
        if ctx.get("kind") not in {"constraint", "data-contract", "external-dep", "actor"}:
            gate.error("R5", f"{ctx.get('id')} invalid context kind")


def _r6_reference_closure(spec: dict, gate: Gate) -> None:
    legal = ref_set(spec)
    source_ids = set(ids_of(spec, "sources"))
    cap_ids, vc_ids, inv_ids = set(ids_of(spec, "capabilities")), set(ids_of(spec, "view-contracts")), set(ids_of(spec, "invariants"))
    slice_ids = set(ids_of(spec, "slices"))

    def check(owner: str, field: str, refs: list[str], universe: set[str] | None = None) -> None:
        for ref in refs:
            if universe is not None and ref not in universe:
                gate.error("R6", f"{owner}.{field} -> {ref!r} is not in the expected universe")
            elif universe is None and ref not in legal:
                gate.error("R6", f"{owner}.{field} -> {ref!r} is unresolved")

    for src in spec.get("sources", []):
        if src.get("kind") not in PRIMARY_KINDS:
            gate.error("R6", f"source {src.get('id')} invalid kind {src.get('kind')!r}")
        for field in ("url", "pin", "captured", "quote", "title"):
            if not src.get(field):
                gate.error("R6", f"source {src.get('id')} missing {field}")

    for proj in spec.get("projects", []):
        check(proj["id"], "evidence-refs", proj.get("evidence-refs", []), source_ids)
    for cap in spec.get("capabilities", []):
        check(cap["id"], "scene-refs", cap.get("scene-refs", []), set(scene_ids(spec)))
        check(cap["id"], "evidence-refs", cap.get("evidence-refs", []), source_ids)
    for vc in spec.get("view-contracts", []):
        check(vc["id"], "invariant-refs", vc.get("invariant-refs", []), inv_ids)
        check(vc["id"], "consumers", vc.get("consumers", []), vc_ids)
        if not vc.get("producer"):
            gate.error("R6", f"{vc['id']} must declare a producer")
    for inv in spec.get("invariants", []):
        check(inv["id"], "evidence-ref", [inv.get("evidence-ref")] if inv.get("evidence-ref") else [], source_ids)
    for sl in spec.get("slices", []):
        check(sl["id"], "depends-on", sl.get("depends-on", []), slice_ids)
    for ctx in spec.get("context-entries", []):
        check(ctx["id"], "evidence-ref", [ctx.get("evidence-ref")] if ctx.get("evidence-ref") else [], source_ids)
    for de in spec.get("difference-entries", []):
        check(de["id"], "evidence-refs", de.get("evidence-refs", []), source_ids)
        for v in de.get("context-verdicts", []):
            if v.get("evidence-ref"):
                check(de["id"], "context-verdicts.evidence-ref", [v["evidence-ref"]], source_ids)
    # side-loaded context must not become a graph member
    for vc in spec.get("view-contracts", []):
        if vc.get("kind") == "side-loaded" and vc.get("format") == "mermaid|html":
            gate.error("R6", f"{vc['id']} side-loaded contract must not use a main-view format")
    if not cap_ids or not vc_ids or not inv_ids:
        gate.error("R6", "capabilities / view-contracts / invariants must all be non-empty")


def _r7_capability_coverage(spec: dict, gate: Gate) -> None:
    scenes = set(scene_ids(spec))
    covered: set[str] = set()
    for cap in spec.get("capabilities", []):
        refs = set(cap.get("scene-refs", []))
        if not refs:
            gate.error("R7", f"{cap['id']} covers no scene")
        covered |= refs
        for field in ("statement", "interaction", "acceptance", "rejected"):
            if not cap.get(field):
                gate.error("R7", f"{cap['id']} missing {field}")
        if not cap.get("evidence-refs"):
            gate.error("R7", f"{cap['id']} has no evidence-refs")
    for scene in sorted(scenes - covered):
        gate.error("R7", f"scene {scene} has no capability covering it")


def _r8_invariants(spec: dict, gate: Gate) -> None:
    for inv in spec.get("invariants", []):
        if not inv.get("guard"):
            gate.error("R8", f"{inv['id']} has no guard")
        if not inv.get("evidence-ref"):
            gate.error("R8", f"{inv['id']} has no evidence-ref")


def _r9_source_labelling(spec: dict, gate: Gate) -> None:
    """CHK-09: every statement declares which of three source kinds it is."""
    for de in spec.get("difference-entries", []):
        did = de["id"]
        kinds = de.get("sources", [])
        if not kinds or not set(kinds) <= SOURCE_KINDS:
            gate.error("R9", f"{did} sources must be a non-empty subset of {sorted(SOURCE_KINDS)}")
            continue
        has_evidence = bool(de.get("evidence-refs"))
        if "evidence" in kinds and not has_evidence:
            gate.error("R9", f"{did} claims evidence but has no evidence-refs (Human ruling is not evidence)")
        if has_evidence and "evidence" not in kinds:
            gate.error("R9", f"{did} carries evidence-refs but does not label itself as evidence")
        if de.get("verdict") == "unknown" and "evidence" in kinds:
            gate.error("R9", f"{did} unknown cannot be labelled evidence")


def _r10_evidence_integrity(spec: dict, gate: Gate) -> None:
    integrity = spec.get("evidence-integrity", {})
    for field in ("statement", "consequence", "no-secondary-as-native"):
        if not integrity.get(field):
            gate.error("R10", f"evidence-integrity.{field} is missing")
    method = spec.get("method-contract", {})
    if "signed-cross-comparison-report" not in method.get("not-applied", []):
        gate.error("R10", "method-contract must declare that no signed report is produced while the scene pin is pending")
    if not method.get("no-silent-substitution"):
        gate.error("R10", "method-contract must state unknown != unsupported")
    for src in spec.get("sources", []):
        if src.get("kind") == "secondary" and not src.get("pin"):
            gate.error("R10", f"secondary source {src['id']} must declare its pin")


def _r11_derivation_shape(spec: dict, gate: Gate) -> None:
    """A derived technical page needs a single IR producer and no second fact source."""
    producers = [vc["id"] for vc in spec.get("view-contracts", []) if vc.get("kind") == "intermediate-representation"]
    if len(producers) != 1:
        gate.error("R11", f"exactly one view-contract must be the IR, got {producers}")
    kinds = Counter(vc.get("kind") for vc in spec.get("view-contracts", []))
    if kinds.get("human-readable", 0) < 2:
        gate.error("R11", "at least two human-readable projections are required (Visual Surface Choice)")
    if kinds.get("side-loaded", 0) != 1:
        gate.error("R11", "exactly one side-loaded context projection is required")
    for rd in spec.get("rejected-defaults", []):
        if not rd.get("reason"):
            gate.error("R11", f"{rd['id']} must state a reason")


def _r12_problem_refinement(spec: dict, gate: Gate) -> None:
    """The Human's second-round refinement is a load condition, NOT a new scene."""
    pr = spec.get("problem-refinement", {})
    for field in ("id", "source", "statement", "diagnosis", "gap-in-prior-design",
                  "not-a-new-scene-set", "loads", "addressed-by"):
        if not pr.get(field):
            gate.error("R12", f"problem-refinement.{field} is missing")
    if "CHK-04" not in pr.get("not-a-new-scene-set", ""):
        gate.error("R12", "problem-refinement must record that the fixed scene set is not expanded")
    lc_ids = set(ids_of(spec, "load-conditions"))
    for ref in pr.get("loads", []):
        if ref not in lc_ids:
            gate.error("R12", f"problem-refinement.loads -> {ref!r} is not a load-condition")
    legal = ref_set(spec) | lc_ids
    for ref in pr.get("addressed-by", []):
        if ref not in legal:
            gate.error("R12", f"problem-refinement.addressed-by -> {ref!r} is unresolved")
    for de in spec.get("difference-entries", []):
        if de.get("scene") in lc_ids:
            gate.error("R12", f"{de['id']} uses a load-condition as its scene")
    if not scene_ids(spec):
        gate.error("R12", "the fixed scene set became empty")
    if not lc_ids:
        gate.error("R12", "load-conditions must be declared separately from scenes")
    for lc in spec.get("load-conditions", []):
        if not lc.get("consequence"):
            gate.error("R12", f"{lc['id']} must state a consequence for the design")


def _r13_doi_function(spec: dict, gate: Gate) -> None:
    """smart == deterministic DOI + explicit theta, never per-call LLM inference."""
    isel = spec.get("information-selection", {})
    doi = isel.get("doi-function", {})
    if not isel.get("id") or not isel.get("statement") or not isel.get("bounded-relation"):
        gate.error("R13", "information-selection must declare id, statement and bounded-relation")
    if doi.get("deterministic") is not True:
        gate.error("R13", "doi-function.deterministic must be true; smart != LLM inference")
    if "非 LLM" not in doi.get("owner", ""):
        gate.error("R13", "doi-function.owner must explicitly exclude LLM inference")
    terms = doi.get("terms", [])
    if len(terms) < 3:
        gate.error("R13", "doi-function needs at least three weighted terms")
    source_ids = set(ids_of(spec, "sources"))
    inv_ids = set(ids_of(spec, "invariants"))
    total = 0.0
    for term in terms:
        if not term.get("id", "").startswith("DOI::T"):
            gate.error("R13", f"doi term {term.get('id')!r} needs the DOI::T prefix")
        weight = term.get("weight")
        if not isinstance(weight, (int, float)) or not 0 < weight <= 1:
            gate.error("R13", f"{term.get('id')} has an invalid weight {weight!r}")
        else:
            total += weight
        if not term.get("definition"):
            gate.error("R13", f"{term.get('id')} has no definition")
        if term.get("evidence-ref") not in source_ids:
            gate.error("R13", f"{term.get('id')} evidence-ref is unresolved")
    if abs(total - 1.0) > 1e-9:
        gate.error("R13", f"DOI weights must sum to 1.0, got {round(total, 6)}")
    thresholds = doi.get("thresholds", {})
    order = [thresholds.get(k) for k in ("overview", "neighborhood", "expand")]
    if any(not isinstance(v, (int, float)) for v in order) or not (order[0] > order[1] > order[2] > 0):
        gate.error("R13", f"thresholds must be strictly decreasing overview > neighborhood > expand > 0, got {order}")
    if "同一" not in doi.get("single-knob", ""):
        gate.error("R13", "compression and expansion must share one ordering and one template")
    for ref in doi.get("invariant-refs", []):
        if ref not in inv_ids:
            gate.error("R13", f"doi-function.invariant-refs -> {ref!r} is unresolved")


def _r14_budget_and_debt(spec: dict, gate: Gate) -> None:
    """A reading budget and first-class execution-time debts."""
    isel = spec.get("information-selection", {})
    rb = isel.get("reading-budget", {})
    if not isinstance(rb.get("max"), int) or rb["max"] <= 0:
        gate.error("R14", "reading-budget.max must be a positive integer")
    if rb.get("silent-drop") is not False:
        gate.error("R14", "reading-budget.silent-drop must be false (no silent loss)")
    if not rb.get("overflow-report"):
        gate.error("R14", "reading-budget.overflow-report is missing")
    if rb.get("evidence-ref") not in set(ids_of(spec, "sources")):
        gate.error("R14", "reading-budget.evidence-ref is unresolved")
    debt = spec.get("debt-schema", {})
    kinds = {k.get("name") for k in debt.get("kinds", [])}
    if not {"gap", "todo", "risk", "sweep"} <= kinds:
        gate.error("R14", "debt-schema must cover gap / todo / risk / sweep")
    for k in debt.get("kinds", []):
        if k.get("severity") not in {"high", "medium", "low"}:
            gate.error("R14", f"{k.get('id')} has an invalid severity")
        if not k.get("definition"):
            gate.error("R14", f"{k.get('id')} has no definition")
    required = set(debt.get("required-fields", []))
    if not {"kind", "severity", "anchor-ref", "discovered-revision", "evidence-ref", "state"} <= required:
        gate.error("R14", "debt-schema.required-fields is incomplete")
    if "resolved" not in debt.get("states", []):
        gate.error("R14", "debt-schema.states must include a terminal state")
    if "不自动" not in debt.get("promotion-rule", ""):
        gate.error("R14", "debt-schema must forbid automatic promotion into WorkItem")
    if not any("ready" in x for x in debt.get("not-in", [])):
        gate.error("R14", "debt-schema must declare debts are outside the ready set")


def _r15_reentry(spec: dict, gate: Gate) -> None:
    """Re-entry reads a delta, and the receipt must never leak into the carrier."""
    reentry = spec.get("information-selection", {}).get("reentry", {})
    fields = set(reentry.get("receipt-fields", []))
    if not {"anchor-token", "carrier-revision", "theta", "seen-item-hashes"} <= fields:
        gate.error("R15", "reentry.receipt-fields is incomplete")
    storage = reentry.get("receipt-storage", "")
    if "carrier" not in storage or "gitignored" not in storage:
        gate.error("R15", "reentry.receipt-storage must state gitignored + outside carrier")
    if set(reentry.get("delta-kinds", [])) != {"added", "changed", "removed", "stable-folded"}:
        gate.error("R15", "reentry.delta-kinds must be exactly the four declared kinds")
    if "content hash" not in reentry.get("item-identity", ""):
        gate.error("R15", "reentry.item-identity must require per-item content hash")
    identity = reentry.get("carrier-identity", "")
    if "baseline=None" not in identity or "逐字节相同" not in identity or "不参与" not in identity:
        gate.error("R15", "reentry.carrier-identity must protect byte identity and keep the receipt out of view-ir")
    if "fail-closed" not in reentry.get("no-hidden-state", ""):
        gate.error("R15", "reentry must fail closed on a missing or corrupt receipt")


def _r16_presentation(spec: dict, gate: Gate) -> None:
    """Cards + DAG are a spatial encoding of the DOI selection, not a reskin."""
    pres = spec.get("presentation", {})
    for field in ("id", "source", "verdict", "replaces", "why", "three-regions",
                  "dag-encoding", "card-lod", "doi-encoding", "constraints",
                  "invariant-refs", "evidence-refs", "addressed-by"):
        if not pres.get(field):
            gate.error("R16", f"presentation.{field} is missing")
    if "采纳" not in pres.get("verdict", "") or "换皮" not in pres.get("verdict", ""):
        gate.error("R16", "presentation.verdict must record conditional adoption and reject a pure reskin")
    if "C::05" not in pres.get("replaces", ""):
        gate.error("R16", "presentation.replaces must name the rule the prior demo violated")
    regions = {r.get("name") for r in pres.get("three-regions", [])}
    if regions != {"anchor-bar", "local-dag", "card-rail", "delta-strip"}:
        gate.error("R16", f"presentation needs exactly the four regions, got {sorted(regions)}")
    dag = pres.get("dag-encoding", {})
    if "DOI>=theta" not in dag.get("scope", ""):
        gate.error("R16", "the DAG must be a DOI-clipped local graph, never the full graph")
    if "确定性" not in dag.get("layout", "") or "禁止" not in dag.get("layout", ""):
        gate.error("R16", "DAG layout must be deterministic and explicitly forbid random layout")
    if "Mermaid" not in dag.get("text-equivalent", ""):
        gate.error("R16", "a text-equivalent projection must exist for diff and byte regression")
    if len(dag.get("edge-encoding", [])) < 3:
        gate.error("R16", "edge semantics need at least three distinct encodings")
    card = pres.get("card-lod", {})
    if len(card.get("levels", [])) < 3:
        gate.error("R16", "card LOD needs at least three levels")
    if "预算" not in card.get("budget", "") or "卡片墙" not in card.get("budget", ""):
        gate.error("R16", "cards must be bounded by the same reading budget, not become a wall")
    if "卡片" not in card.get("debt", ""):
        gate.error("R16", "debts must be cards, never DAG nodes")
    encoding = pres.get("doi-encoding", {})
    if encoding.get("no-color-only") is not True or len(encoding.get("channels", [])) < 2:
        gate.error("R16", "DOI encoding must not rely on colour alone and needs >=2 channels")
    if len(pres.get("constraints", [])) < 4:
        gate.error("R16", "presentation constraints are incomplete")
    source_ids = set(ids_of(spec, "sources"))
    inv_ids = set(ids_of(spec, "invariants"))
    legal = ref_set(spec)
    for ref in (pres.get("evidence-refs", []) + dag.get("evidence-refs", [])
                + card.get("evidence-refs", [])):
        if ref not in source_ids:
            gate.error("R16", f"presentation evidence-ref -> {ref!r} is unresolved")
    for ref in pres.get("invariant-refs", []):
        if ref not in inv_ids:
            gate.error("R16", f"presentation.invariant-refs -> {ref!r} is unresolved")
    for ref in pres.get("addressed-by", []):
        if ref not in legal:
            gate.error("R16", f"presentation.addressed-by -> {ref!r} is unresolved")


